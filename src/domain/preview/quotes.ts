/**
 * 오늘의 명언. 날짜가 같으면 누가 언제 열어도 같은 문장이 나온다.
 *
 * KST(+9) 를 더하고 나누는 이유: UTC 기준으로 자르면 한국에서는 아침 9시에 명언이 바뀐다.
 * '오늘의' 명언이라면 한국 자정에 넘어가야 한다.
 */
export function pickDailyQuote(now: number = Date.now()): { quote: InvestorQuote; index: number } {
  const KST_OFFSET_MS = 9 * 60 * 60 * 1000;
  const DAY_MS = 24 * 60 * 60 * 1000;
  const index = Math.floor((now + KST_OFFSET_MS) / DAY_MS) % INVESTOR_QUOTES.length;

  return { quote: INVESTOR_QUOTES[index], index };
}
